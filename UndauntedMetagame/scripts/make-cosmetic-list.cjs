// Builds scripts/grant-cosmetics.ids.json, the list of cosmetic ids grant-cosmetics.cjs may grant.
// Runs offline against a COPY of undaunted.db (opened read-only, never written):
//   node scripts/make-cosmetic-list.cjs <copy-of-undaunted.db>
// An id is client-known when it is in our store/progression data (store_catalog, store_item_kinds, store_ladyluck,
// progression_config rewards) or at least 2 real accounts already hold it. Ids held by exactly one account and
// found nowhere else are listed as unconfirmed and never granted.
// The grant kind comes from the client's stackable flag (store_ladyluck itemKinds, then store_item_kinds, the same
// order as GrantKind in freestore.ts); for anything else, from how real players hold it (stacked vs instanced).
const fs = require('node:fs');
const path = require('node:path');
const Database = require('better-sqlite3');
const Vendor = (F) => require(path.join(__dirname, '../src/vendor', F));
const DbPath = process.argv[2];
if (!DbPath) { console.error('usage: make-cosmetic-list.cjs <copy-of-undaunted.db>'); process.exit(2); }

// Sources (a) and (b)
const Sources = {};
const Note = (Id, Source) => { if (typeof Id === 'string' && /^[A-Za-z][A-Za-z0-9]*_[A-Za-z0-9_-]+$/.test(Id)) (Sources[Id] ??= new Set()).add(Source); };
const Walk = (O, Key, Source) => {
  if (Array.isArray(O)) O.forEach((X) => Walk(X, Key, Source));
  else if (O && typeof O === 'object') for (const [K, V] of Object.entries(O)) { if (K === Key) Note(V, Source); Walk(V, Key, Source); }
};
Walk(Vendor('store_catalog.json'), 'catalogId', 'store_catalog');
Walk(Vendor('store_ladyluck.json').offers, 'catalogId', 'store_ladyluck');
Walk(Vendor('progression_config.json'), 'catalog_id', 'progression_config');
const ItemKinds = Vendor('store_item_kinds.json');
const LadyLuckKinds = Vendor('store_ladyluck.json').itemKinds;
for (const Id of Object.keys(ItemKinds)) if (!Id.startsWith('_')) Note(Id, 'store_item_kinds');
for (const Id of Object.keys(LadyLuckKinds)) Note(Id, 'store_ladyluck');
// store_middleman.json (exchange-slot entitlements) and trials_pool.json (behemoth/trial rows) name no item ids.

// Source (c): what real accounts hold
const Db = new Database(DbPath, {readonly: true, fileMustExist: true});
const Held = {};
for (const R of Db.prepare('SELECT c.userId, i.stackedItems, i.instancedItems FROM inventories i LEFT JOIN characters c ON c.characterId = i.characterId').iterate()) {
  const Add = (Id, Kind) => { const H = Held[Id] ??= {accounts: new Set(), stacked: 0, instanced: 0}; H.accounts.add(R.userId ?? `orphan:${Math.random()}`); H[Kind]++; };
  try { for (const S of JSON.parse(R.stackedItems)) if (typeof S?.catalogId === 'string' && Number(S.quantity) > 0) Add(S.catalogId, 'stacked'); } catch {}
  try { for (const I of JSON.parse(R.instancedItems)) if (typeof I?.catalogId === 'string') Add(I.catalogId, 'instanced'); } catch {}
}
Db.close();

const Categories = [
  ['AR_', 'armour'], ['WP_', 'weapon_skins'], ['LT_', 'lantern_skins'], ['EM_', 'emotes'], ['EJ_', 'emoji'],
  ['BNC_', 'banners'], ['QI_FLARE_', 'flares'], ['DYE_', 'dyes'], ['TITLE_', 'titles'], ['AC_', 'accessories'],
  ['CC_', 'appearance'], ['MP_', 'special'], ['BN_', 'special'], ['FL_', 'special'], ['GD_', 'special'],
];
const NotCosmetic = [
  [/^CURRENCY_/, 'currency'], [/^TOKEN_/, 'token / consumable'], [/^CELL/i, 'cell'], [/^(ORB|GEM)_/, 'upgrade material'],
  [/^PART_/, 'weapon part (gear)'], [/^BREAK_|^GATHER_/, 'behemoth part / gathered material'], [/^Container_/, 'reward container'],
  [/^COL_/, 'lore collection page, not a cosmetic'], [/^QI_(?!FLARE_)/, 'consumable (potion / grenade / basic flare)'], [/^TY_/, 'toy: firework / gift, used up on use'],
];
const Out = {_comment: [
  'Generated by scripts/make-cosmetic-list.cjs from our vendor data and a read-only copy of the DR database. Do not edit by hand.',
  'grant: id -> [category, kind, holders, source]. unconfirmed / excluded: id -> [category or prefix, reason]. Holder counts are distinct accounts in that copy.',
], generatedFrom: path.basename(DbPath), grant: {}, unconfirmed: {}, excluded: {}};
for (const Id of [...new Set([...Object.keys(Sources), ...Object.keys(Held)])].sort()) {
  const H = Held[Id];
  const Holders = H ? H.accounts.size : 0;
  const InSources = Sources[Id] !== undefined;
  const Bad = NotCosmetic.find(([Re]) => Re.test(Id));
  const Category = Categories.find(([P]) => Id.startsWith(P))?.[1];
  const ClientKind = LadyLuckKinds[Id] ?? ItemKinds[Id];
  const Kind = ClientKind ?? (H ? (H.instanced > H.stacked ? 'instanced' : 'stacked') : undefined);
  let Reason;
  if (/TEST|DEBUG|UNEQUIPPED|PLACEHOLDER|(^|_)DEV(_|$)/i.test(Id)) Reason = 'dev / test / placeholder item';
  else if (Bad) Reason = Bad[1];
  else if (!Category) Reason = 'not a cosmetic prefix';
  // Real weapons, armour and lanterns are instanced items with stats; their skins are stacked (or named by the store)
  else if (['armour', 'weapon_skins', 'lantern_skins'].includes(Category) && !InSources && Kind === 'instanced')
    Reason = 'gear with stats (held instanced, not a store/reward skin)';
  else if (!InSources && Holders < 2) { Out.unconfirmed[Id] = [Category, `held by ${Holders} account, in no data file`]; continue; }
  else if (Kind !== 'stacked' && Kind !== 'instanced') Reason = 'grant kind unknown (nobody holds it and the client kind list does not name it)';
  if (Reason) { Out.excluded[Id] = [Category ?? Id.split('_')[0] + '_', Reason]; continue; }
  Out.grant[Id] = [Category, Kind, Holders, [...(Sources[Id] ?? [])].join('+') || 'held'];
}
fs.writeFileSync(path.join(__dirname, 'grant-cosmetics.ids.json'), JSON.stringify(Out, null, 1) + '\n');
const Count = {};
for (const [C, K] of Object.values(Out.grant)) Count[`${C}:${K}`] = (Count[`${C}:${K}`] ?? 0) + 1;
console.log(JSON.stringify({grant: Object.keys(Out.grant).length, unconfirmed: Object.keys(Out.unconfirmed).length, excluded: Object.keys(Out.excluded).length, byCategory: Count}, null, 1));
